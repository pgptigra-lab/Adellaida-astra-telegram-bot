def format_aspect_interpretations(result):
    lines = ["", "🔗 ЧТО ОЗНАЧАЮТ АСПЕКТЫ"]
    if not result["aspects"]:
        lines.append("В этой карте нет аспектов из выбранного набора с заданными орбисами.")
        return "\n".join(lines)

    for first, aspect, second, orb in result["aspects"]:
        meaning, strengths, advice = ASPECT_INTERPRETATIONS[aspect]
        first_theme = PLANET_MEANINGS[first]
        second_theme = PLANET_MEANINGS[second]
        pair_note = ASPECT_PAIR_NOTES.get((first, second)) or ASPECT_PAIR_NOTES.get((second, first))
        lines.extend([
            "",
            f"✦ {first} — {aspect} — {second} (орбис {orb}°)",
            f"Связаны темы: {first_theme} и {second_theme}.",
            pair_note or aspect_pair_note(first, second),
        ])
        if not pair_note:
            lines.extend([meaning, strengths, f"Практический ориентир: {advice}"])

    lines.extend([
        "",
        "Важно: это общие символические значения аспектов. Их смысл зависит также от знаков, домов и всей карты; это не научная оценка личности и не прогноз.",
    ])
    return "\n".join(lines)
